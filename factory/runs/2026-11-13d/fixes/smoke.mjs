import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const OUT = process.argv[2] || '.';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push('pageerror: ' + e.message));
page.on('response', r => { if (r.status() >= 400) errors.push('http ' + r.status() + ' ' + r.url()); });
await page.route('https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.js', r => r.fulfill({ path: '/tmp/three/build/three.module.js', contentType: 'text/javascript' }));
await page.goto('http://localhost:8765/index.html');
await page.waitForFunction(() => window.SolarAtlas?.journey, null, { timeout: 30000 });
const settle = () => page.waitForFunction(() => !SolarAtlas.journey.busy, null, { timeout: 90000 }).then(() => page.waitForTimeout(1500));
const state = () => page.evaluate(() => ({ level: SolarAtlas.journey.level, piece: SolarAtlas.journey.piece }));
const log = ['vr button: ' + !!(await page.$('#vr'))];
await page.selectOption('#language', 'pt'); log.push('lang: ' + await page.evaluate(() => document.documentElement.dataset.lang));
await page.evaluate(() => SolarAtlas.journey.go('galaxy')); await settle();
await page.screenshot({ path: OUT + '/1-galaxy-pt.png' });
const nameBox = re => page.evaluate(s => { const b = [...document.querySelectorAll('.jtag.piece')].find(e => new RegExp(s).test(e.textContent)); const r = b?.querySelector('.name').getBoundingClientRect(); return r ? { x: r.left + r.width / 2, y: r.top + r.height / 2 } : null; }, re);
const hold = async c => { for (let i = 0; i < 40; i++) { await page.evaluate(c => SolarAtlas.simulateHand({ present: true, gesture: 'point', cursor: c, openness: 1 }), { x: c.x / 1440, y: c.y / 900 }); await page.waitForTimeout(60); } await page.evaluate(() => SolarAtlas.simulateHand({ present: false })); await settle(); };
const mw = await nameBox('Via Láctea'); log.push('Via Láctea label at ' + JSON.stringify(mw));
await hold(mw); log.push('hand holds on "VIA LÁCTEA" label → ' + JSON.stringify(await state()));
await page.screenshot({ path: OUT + '/2-milky-way-by-hand-pt.png' });
await page.evaluate(() => SolarAtlas.journey.back()); await settle();
const sg = await nameBox('Sagit'); log.push('Sgr A* label at ' + JSON.stringify(sg));
await hold(sg); log.push('hand holds on "SAGITÁRIO A*" label → ' + JSON.stringify(await state()));
await page.evaluate(() => SolarAtlas.journey.back()); await settle();
await page.evaluate(() => SolarAtlas.journey.open('betelgeuse')); await settle();
log.push('betelgeuse distance: ' + await page.$$eval('#info .facts > div', ds => ds.map(d => d.innerText.replace(/\n/g, ' | ')).find(t => /Dist/.test(t))));
await page.screenshot({ path: OUT + '/3-betelgeuse-pt.png' });
log.push('errors: ' + (errors.length ? errors.join(' | ') : 'none'));
console.log(log.join('\n')); await browser.close();
