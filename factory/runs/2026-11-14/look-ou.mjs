import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const OUT = process.argv[2] || '.';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.route('https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.js', r => r.fulfill({ path: '/tmp/three/build/three.module.js', contentType: 'text/javascript' }));
await page.goto('http://localhost:8765/index.html');
await page.waitForFunction(() => window.SolarAtlas?.journey, null, { timeout: 30000 });
const settle = () => page.waitForFunction(() => !SolarAtlas.journey.busy, null, { timeout: 90000 }).then(() => page.waitForTimeout(2500));
const labels = () => page.$$eval('.jtag', es => es.filter(e => e.style.display !== 'none').map(e => e.innerText.trim()));
await page.evaluate(() => SolarAtlas.journey.open('observable-universe')); await settle();
await page.screenshot({ path: OUT + '/observable-universe/1-open.png' });
console.log('info:', await page.$eval('#info', e => e.innerText.slice(0, 400).replace(/\n/g, ' ')));
await page.evaluate(() => SolarAtlas.journey.back()); await settle();
console.log('universe labels:', JSON.stringify(await labels()));
await page.screenshot({ path: OUT + '/observable-universe/2-universe-level.png' });
await page.evaluate(() => SolarAtlas.journey.open('cosmic-web')); await settle();
console.log('cosmic-web open labels:', JSON.stringify(await labels()));
console.log('errors:', errors.length ? errors : 'none'); await browser.close();
